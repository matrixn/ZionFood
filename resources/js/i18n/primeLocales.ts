function build(locale: AdditionalLocale) {
    const translated = Object.fromEntries(wordKeys.map((key, index) => [key, words[locale][index]])) as Record<
        (typeof wordKeys)[number],
        string
    >;
    return {
        ...translated,
        ...calendars[locale],
        emptyFilterMessage: translated.emptyMessage,
        firstDayOfWeek: 1,
        dateFormat: 'dd.mm.yy',
        aria: Object.fromEntries(ariaKeys.map((key, index) => [key, aria[locale][index]])) as Record<
            (typeof ariaKeys)[number],
            string
        >,
    };
}
