import { test, expect as baseExpect } from '@playwright/test';
const expect = baseExpect.configure({ timeout: 15000 });
import { readFileSync } from 'node:fs';

const fixture = (admin = false) => JSON.parse(readFileSync(admin ? 'storage/app/private/browser-email-admin.json' : 'storage/app/private/browser-account.json', 'utf8'));

test('restaurant creates its own ingredient and a priced portion with ordered ingredients inside the wizard', async ({ page, browser }) => {
    test.setTimeout(150000);
    page.setDefaultTimeout(15000);
    const account = fixture();
    const errors: string[] = [];
    page.on('pageerror', e => errors.push(e.message));
    await page.goto('/login');
    await page.locator('#email').fill(account.email);
    await page.locator('#password').fill(account.password);
    await page.getByRole('button', { name: 'Autentificare', exact: true }).click();
    await expect(page).toHaveURL(/\/app\/locations\//, { timeout: 20000 });
    const base = `/app/locations/${account.location}`;
    await page.goto(base + '/setup/menu');
    await page.getByRole('button', { name: 'Gestionează ingredientele', exact: true }).click();
    const manager = page.getByTestId('ingredient-manager');
    await manager.getByRole('button', { name: 'Adaugă ingredient', exact: true }).click();
    const edit = page.getByRole('dialog', { name: 'Ingredient', exact: true });
    await edit.getByRole('textbox', { name: 'Denumire ingredient (RO)', exact: true }).fill('Sos propriu test');
    await edit.getByRole('textbox', { name: 'Denumire ingredient (EN, opțional)', exact: true }).fill('House test sauce');
    await edit.getByRole('checkbox', { name: 'Conține alergeni (*)', exact: true }).check();
    await edit.getByRole('checkbox', { name: 'Poate proveni din produse congelate (**)', exact: true }).check();
    await edit.getByRole('button', { name: 'Salvează ingredientul', exact: true }).click();
    await expect(edit).toHaveCount(0);
    await manager.getByRole('textbox', { name: 'Caută ingrediente', exact: true }).fill('Sos propriu test');
    await expect(manager.getByRole('heading', { name: 'Sos propriu test * / **', exact: true })).toBeVisible();
    await page.getByRole('dialog', { name: 'Ingrediente', exact: true }).locator('.p-dialog-close-button').click();
    await expect(page).toHaveURL(base + '/setup/menu');
    await page.getByRole('button', { name: 'Adaugă produs', exact: true }).click();
    const product = page.getByRole('dialog');
    await product.getByRole('textbox', { name: 'Nume', exact: true }).fill('Feta Saganaki test');
    await product.getByRole('spinbutton', { name: 'Preț (RON)', exact: true }).fill('51,99');
    await product.getByRole('textbox', { name: 'Gramaj / porție', exact: true }).fill('350 g');
    const expected = ['Branza feta', 'Sos rosii', 'Ceapa rosie', 'Masline', 'Rosii cherry', 'Ulei de masline', 'Oregano', 'Bagheta', 'Sos propriu test'];
    for (const name of expected) {
        await product.getByRole('textbox', { name: 'Caută ingrediente', exact: true }).fill(name);
        await product.getByTestId('product-ingredients').getByRole('checkbox', { name: new RegExp('^' + name + '(?: |$)') }).check();
        await expect(product.getByTestId('selected-ingredients')).toContainText(name);
    }
    const saved = page.waitForResponse(r => r.url().endsWith(`/api/v1/locations/${account.location}/items`) && r.request().method() === 'POST');
    await product.getByRole('button', { name: 'Salvează produsul', exact: true }).click();
    const response = await saved;
    expect(response.status()).toBe(201);
    const item = await response.json();
    expect(item.price).toBe(5199);
    expect(item.portion_size).toBe('350 g');
    expect(item.ingredients.map((i: {name:string}) => i.name)).toEqual(expected);
    await expect(page.getByRole('dialog')).toHaveCount(0);
    await expect(page).toHaveURL(base + '/setup/menu');
    await page.getByRole('button', { name: 'Gestionează ingredientele', exact: true }).click();
    await manager.getByRole('textbox', { name: 'Caută ingrediente', exact: true }).fill('Sos propriu test');
    await manager.getByRole('button', { name: 'Editează', exact: true }).click();
    await edit.getByRole('checkbox', { name: 'Disponibil pentru selecție', exact: true }).uncheck();
    await edit.getByRole('button', { name: 'Salvează ingredientul', exact: true }).click();
    await expect(edit).toHaveCount(0);
    await expect(manager.getByText('Ascuns din selecțiile noi', { exact: true })).toBeVisible();
    await page.getByRole('dialog', { name: 'Ingrediente', exact: true }).locator('.p-dialog-close-button').click();
    await page.getByRole('button', { name: 'Editează Feta Saganaki test', exact: true }).click();
    await expect(page.getByRole('dialog').getByRole('status')).toContainText('ingrediente ascunse sau eliminate');
    await page.getByRole('dialog').locator('.p-dialog-close-button').click();
    const guest = await browser.newContext();
    const menu = await guest.newPage();
    await menu.goto(`/store/${account.location}`);
    const card = menu.getByRole('button').filter({ has: menu.getByRole('heading', { name: 'Feta Saganaki test', exact: true }) });
    await expect(card).toContainText('350 g');
    await expect(card).toContainText('51,99');
    await expect(card).toContainText('Sos propriu test * / **');
    await expect(menu.getByTestId('allergen-notice')).toContainText('Moluște');
    await expect(menu.getByTestId('allergen-notice')).toContainText('Ingredientele marcate pot proveni din produse congelate.');
    await menu.setViewportSize({ width: 390, height: 844 });
    expect(await menu.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    await menu.screenshot({ path: 'test-results/ingredients-storefront-mobile.png', fullPage: true });
    await menu.getByTestId('language-selector').click();
    await menu.getByRole('option', { name: 'English', exact: true }).click();
    await expect(card).toContainText('House test sauce * / **');
    await expect(menu.getByTestId('allergen-notice')).toContainText('Molluscs');
    await guest.close();
    await page.setViewportSize({ width: 390, height: 844 });
    await page.getByRole('button', { name: 'Editează Feta Saganaki test', exact: true }).click();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    await page.screenshot({ path: 'test-results/ingredients-product-editor-mobile.png', fullPage: true });
    await page.getByRole('dialog').locator('.p-dialog-close-button').click();
    await page.getByTestId('language-selector').click();
    await page.getByRole('option', { name: 'English', exact: true }).click();
    await page.getByRole('button', { name: 'Edit Feta Saganaki test', exact: true }).click();
    await expect(page.getByRole('spinbutton', { name: 'Price (RON)', exact: true })).toHaveValue(/51\.99/);
    await page.getByRole('dialog').locator('.p-dialog-close-button').click();
    await page.getByTestId('language-selector').click();
    await page.getByRole('option', { name: 'Română', exact: true }).click();
    expect(errors).toEqual([]);
});

test('platform administrator edits hides and removes shared ingredients with review filters', async ({ page }) => {
    test.setTimeout(90000);
    page.setDefaultTimeout(15000);
    const account = fixture(true);
    const globalName = `Ingredient comun browser ${Date.now()}`;
    await page.goto('/login');
    await page.locator('#email').fill(account.email);
    await page.locator('#password').fill(account.password);
    await page.getByRole('button', { name: 'Autentificare', exact: true }).click();
    await expect(page).toHaveURL(/\/app\/locations\//, { timeout: 20000 });
    await page.goto('/admin/ingredients');
    const manager = page.getByTestId('ingredient-manager');
    await manager.getByRole('checkbox', { name: 'Doar ingrediente de verificat', exact: true }).check();
    await manager.getByRole('textbox', { name: 'Caută ingrediente', exact: true }).fill('Mozzarella');
    await expect(manager.getByRole('heading', { name: 'Mozzarella *', exact: true })).toBeVisible();
    await manager.getByRole('checkbox', { name: 'Doar ingrediente de verificat', exact: true }).uncheck();
    await manager.getByRole('button', { name: 'Adaugă ingredient', exact: true }).click();
    const edit = page.getByRole('dialog');
    await edit.getByRole('textbox', { name: 'Denumire ingredient (RO)', exact: true }).fill(globalName);
    await edit.getByRole('checkbox', { name: 'Conține alergeni (*)', exact: true }).check();
    await edit.getByRole('checkbox', { name: 'Poate proveni din produse congelate (**)', exact: true }).check();
    await edit.getByRole('button', { name: 'Salvează ingredientul', exact: true }).click();
    await expect(edit).toHaveCount(0);
    await manager.getByRole('textbox', { name: 'Caută ingrediente', exact: true }).fill(globalName);
    await manager.getByRole('button', { name: 'Editează', exact: true }).click();
    await edit.getByRole('checkbox', { name: 'Disponibil pentru selecție', exact: true }).uncheck();
    await edit.getByRole('button', { name: 'Salvează ingredientul', exact: true }).click();
    await expect(edit).toHaveCount(0);
    await expect(manager.getByText('Ascuns din selecțiile noi', { exact: true })).toBeVisible();
    await page.setViewportSize({ width: 390, height: 844 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    await manager.getByRole('button', { name: 'Elimină ingredientul', exact: true }).click();
    await page.getByRole('alertdialog').getByRole('button', { name: 'Confirmă', exact: true }).click();
    await expect(manager.getByRole('heading', { name: globalName + ' * / **', exact: true })).toHaveCount(0);
});
