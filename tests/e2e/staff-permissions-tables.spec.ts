import { test, expect as baseExpect, type Page } from '@playwright/test';
import { readFileSync } from 'node:fs';
const expect = baseExpect.configure({ timeout: 15000 });
const fixture = (closed = false) => JSON.parse(readFileSync(`storage/app/private/${closed ? 'browser-closed-window' : 'browser-permissions'}.json`, 'utf8'));
async function login(page: Page, staff = false, closed = false) {
    page.setDefaultTimeout(15000);
    const account = fixture(closed);
    await page.goto('/login');
    await page.locator('#email').fill(staff ? account.staff_email : account.email);
    await page.locator('#password').fill(staff ? account.staff_password : account.password);
    await page.getByRole('button', { name: 'Autentificare', exact: true }).click();
    await expect(page).toHaveURL(/\/app\/locations\//);
    return account;
}
async function permission(page: Page, feature: string, level: string) {
    const dialog = page.getByRole('dialog');
    const combo = dialog.getByTestId('staff-permissions').getByRole('combobox', { name: feature, exact: true });
    await combo.click();
    const list = await combo.getAttribute('aria-controls');
    await page.locator(`[id="${list}"]`).getByRole('option', { name: level, exact: true }).click();
}

test('owner configures hidden, read-only and editable features independently for one employee', async ({ page, browser }) => {
    test.setTimeout(180000);
    const account = await login(page);
    const base = `/app/locations/${account.location}`;
    const context = await browser.newContext();
    const staff = await context.newPage();
    await login(staff, true);
    const nav = staff.getByRole('navigation', { name: 'Navigare restaurant', exact: true });
    await expect(nav.getByRole('link', { name: 'Rezervări', exact: true })).toHaveCount(0);
    await expect(nav.getByRole('link', { name: 'Administrare meniu', exact: true })).toHaveCount(0);
    await staff.goto(base + '/kitchen');
    await expect(staff.getByText('Permission Browser Guest', { exact: false })).toBeVisible();
    await expect(staff.getByRole('button', { name: 'Acceptă comanda', exact: true })).toHaveCount(0);
    await page.goto(base + '/staff');
    const emailBox = await page.locator('input[type="email"]').boundingBox();
    const roleBox = await page.locator('form').getByRole('combobox').first().boundingBox();
    expect(emailBox).not.toBeNull();
    expect(roleBox).not.toBeNull();
    expect(emailBox!.x + emailBox!.width).toBeLessThanOrEqual(roleBox!.x);
    const member = page.locator('section').filter({ has: page.getByRole('heading', { name: 'Membrii organizației', exact: true }) }).locator('div').filter({ has: page.getByText(account.staff_email, { exact: true }) }).filter({ has: page.getByRole('button', { name: 'Editează accesul', exact: true }) }).last();
    await member.getByRole('button', { name: 'Editează accesul', exact: true }).click();
    await permission(page, 'Comenzi', 'Fără acces');
    await permission(page, 'Bucătărie', 'Vizualizare și modificare');
    await permission(page, 'Meniu', 'Doar vizualizare');
    await permission(page, 'Mese și QR', 'Doar vizualizare');
    await page.getByRole('button', { name: 'Salvează accesul', exact: true }).click();
    await expect(page.getByRole('dialog')).toHaveCount(0);
    await staff.reload();
    await expect(nav.getByRole('link', { name: 'Comenzi', exact: true })).toHaveCount(0);
    await expect(staff.getByRole('button', { name: 'Acceptă comanda', exact: true })).toBeVisible();
    await staff.getByRole('button', { name: 'Acceptă comanda', exact: true }).click();
    await expect(staff.getByRole('button', { name: 'Începe pregătirea', exact: true })).toBeVisible();
    expect((await staff.request.get(`/api/v1/locations/${account.location}/orders`, {headers: {Accept: 'application/json', Referer: staff.url()}})).status()).toBe(403);
    await staff.goto(base + '/menu');
    await expect(staff.getByRole('heading', { name: 'Preparat de test', exact: true })).toBeVisible();
    await expect(staff.getByRole('button', { name: 'Adaugă produs', exact: true })).toHaveCount(0);
    await staff.goto(base + '/tables');
    await expect(staff.getByTestId('table-card')).toHaveCount(2);
    await expect(staff.getByRole('button', { name: 'Activează toate mesele', exact: true })).toHaveCount(0);
    await expect(staff.getByRole('button', { name: 'Închide meniul mesei', exact: true })).toHaveCount(0);
    await member.getByRole('button', { name: 'Editează accesul', exact: true }).click();
    await permission(page, 'Comenzi', 'Vizualizare și modificare');
    await permission(page, 'Bucătărie', 'Doar vizualizare');
    await permission(page, 'Meniu', 'Vizualizare și modificare');
    await page.getByRole('button', { name: 'Salvează accesul', exact: true }).click();
    await expect(page.getByRole('dialog')).toHaveCount(0);
    await staff.goto(base + '/menu');
    await expect(staff.getByRole('button', { name: 'Adaugă produs', exact: true })).toBeVisible();
    await staff.goto(base + '/orders');
    await staff.getByRole('row').filter({hasText: account.order.slice(-8)}).getByRole('button').click();
    const drawer = staff.getByRole('dialog');
    await drawer.getByRole('combobox', { name: 'Starea următoare', exact: true }).click();
    await staff.getByRole('option', { name: 'În pregătire', exact: true }).click();
    await drawer.getByRole('button', { name: 'Actualizează comanda', exact: true }).click();
    await expect(drawer.getByText('În pregătire', { exact: true })).toBeVisible();
    await page.screenshot({ path: 'test-results/staff-feature-permissions.png', fullPage: true });
    await context.close();
});

test('bulk table controls preserve permanent QR and scope changes to the selected room', async ({ page }) => {
    test.setTimeout(90000);
    const account = await login(page);
    await page.goto(`/app/locations/${account.location}/tables`);
    await page.getByRole('button', { name: 'Dezactivează toate mesele', exact: true }).click();
    await page.getByRole('alertdialog').getByRole('button', { name: 'Confirmă', exact: true }).click();
    const cards = page.getByTestId('table-card');
    await expect(cards.locator('[data-state="open"]')).toHaveCount(0);
    await expect(cards.first()).toHaveAttribute('data-state', 'table_closed');
    const salon = cards.filter({ has: page.getByRole('heading', { name: 'T1 · Salon', exact: true }) });
    const terrace = cards.filter({ has: page.getByRole('heading', { name: 'T2 · Terasă', exact: true }) });
    await salon.locator('summary').click();
    const url = await salon.getByRole('link', { name: 'Deschide linkul QR', exact: true }).getAttribute('href');
    await page.getByRole('button', { name: 'Activează Salon', exact: true }).click();
    await expect(salon).toHaveAttribute('data-state', 'open');
    await expect(terrace).toHaveAttribute('data-state', 'table_closed');
    await expect(salon.getByRole('link', { name: 'Deschide linkul QR', exact: true })).toHaveAttribute('href', url!);
    await page.getByRole('button', { name: 'Activează toate mesele', exact: true }).click();
    await expect(terrace).toHaveAttribute('data-state', 'open');
    await page.setViewportSize({ width: 390, height: 844 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: 'test-results/table-rooms-mobile.png', fullPage: true });
});

test('a manually enabled table outside ordering hours is consistently unavailable to the QR guest', async ({ page, browser }) => {
    const account = await login(page, false, true);
    await page.goto(`/app/locations/${account.location}/tables`);
    const card = page.getByTestId('table-card').first();
    await expect(card).toHaveAttribute('data-state', 'outside_hours');
    await expect(card.getByText('Masa este activată de personal.', { exact: true })).toBeVisible();
    await card.locator('summary').click();
    const qr = (await card.getByRole('link', { name: 'Deschide linkul QR', exact: true }).getAttribute('href'))!;
    const context = await browser.newContext();
    const guest = await context.newPage();
    const response = await guest.goto(qr);
    expect(response!.status()).toBe(200);
    await expect(guest.getByText('Comenzile la masă nu sunt disponibile în afara programului restaurantului.', { exact: false })).toBeVisible();
    await expect(guest.getByRole('button', { name: 'Conectează masa', exact: true })).toHaveCount(0);
    await guest.screenshot({ path: 'test-results/table-outside-hours.png', fullPage: true });
    await context.close();
});
