import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';

test('setup integrates real editors and keeps grouped navigation and the wizard after saves', async ({ page }) => {
    test.setTimeout(120000);
    const account = JSON.parse(readFileSync('storage/app/private/browser-account.json', 'utf8'));
    const errors: string[] = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto('/login');
    await page.locator('#email').fill(account.email);
    await page.locator('#password').fill(account.password);
    await page.getByRole('button', { name: 'Autentificare', exact: true }).click();
    await expect(page).toHaveURL(/\/app\/locations\//, { timeout: 20000 });
    const base = `/app/locations/${account.location}`;
    await page.goto(base + '/setup/hours');
    const nav = page.getByRole('navigation', { name: 'Navigare restaurant', exact: true });
    await expect(nav.getByRole('link').first()).toHaveText('Pregătește restaurantul');
    await expect(nav.getByRole('link').first()).toHaveAttribute('aria-current', 'page');
    await expect(nav.getByRole('heading', { name: 'Operațiuni', exact: true })).toBeVisible();
    await expect(nav.getByRole('heading', { name: 'Administrarea restaurantului', exact: true })).toBeVisible();
    await expect(nav.getByRole('heading', { name: 'Conectări', exact: true })).toBeVisible();
    await expect(page.locator('header')).toHaveCount(1);
    await page.locator('input[type=time]').first().fill('10:00');
    let prompted = false;
    page.once('dialog', async dialog => { prompted = true; await dialog.dismiss(); });
    await page.getByRole('link', { name: 'Înainte →', exact: true }).click();
    expect(prompted).toBe(true);
    await expect(page).toHaveURL(base + '/setup/hours');
    await page.getByRole('button', { name: 'Salvează setările', exact: true }).click();
    await expect(page.getByRole('status').filter({ hasText: 'Setările locației au fost salvate.' })).toBeVisible();
    await expect(page).toHaveURL(base + '/setup/hours');
    await page.getByRole('link', { name: 'Înainte →', exact: true }).click();
    await expect(page).toHaveURL(base + '/setup/delivery');
    await expect(page.getByTestId('setup-step-heading')).toHaveText('Zone de livrare');
    await page.getByRole('button', { name: 'Adaugă zonă', exact: true }).click();
    await page.getByRole('textbox', { name: 'Nume', exact: true }).last().fill('Zona wizard');
    await page.getByRole('textbox', { name: 'Prefix poștal', exact: true }).fill('24');
    await page.getByRole('button', { name: 'Salvează setările', exact: true }).click();
    await expect(page.getByRole('status').filter({ hasText: 'Setările locației au fost salvate.' })).toBeVisible();
    await expect(page).toHaveURL(base + '/setup/delivery');
    await page.reload();
    await expect(page.getByRole('textbox', { name: 'Nume', exact: true }).last()).toHaveValue('Zona wizard');
    await page.goto(base + '/setup/menu');
    await page.getByRole('button', { name: 'Categorie', exact: true }).click();
    await page.getByRole('textbox', { name: 'Numele categoriei', exact: true }).fill('Categorie wizard');
    await page.getByRole('button', { name: 'Salvează categoria', exact: true }).click();
    await expect(page.getByRole('dialog')).toHaveCount(0);
    await expect(page.getByText('Categorie wizard', { exact: true }).first()).toBeVisible();
    await expect(page).toHaveURL(base + '/setup/menu');
    await page.goto(base + '/setup/branding');
    await page.getByRole('textbox', { name: 'Numele restaurantului', exact: true }).fill('Restaurant Wizard');
    await page.getByRole('button', { name: 'Salvează identitatea', exact: true }).click();
    await expect(page.getByRole('status')).toBeVisible();
    await expect(page).toHaveURL(base + '/setup/branding');
    await page.goto(base + '/setup/staff');
    await expect(page.getByRole('button', { name: 'Trimite invitația', exact: true })).toBeVisible();
    await expect(page.getByRole('textbox', { name: 'E-mail', exact: true })).toBeVisible();
    await page.goto(base + '/setup/locations');
    await expect(page.getByRole('link', { name: 'Configurează locația', exact: true })).toBeVisible();
    await page.getByRole('link', { name: 'Configurează locația', exact: true }).click();
    await expect(page).toHaveURL(base + '/setup/basics');
    await page.screenshot({ path: 'test-results/wizard-navigation-desktop.png', fullPage: true });
    await page.getByTestId('language-selector').click();
    await page.getByRole('option', { name: 'English', exact: true }).click();
    await page.goto(base + '/setup/staff');
    await expect(page.getByRole('navigation', { name: 'Restaurant navigation' }).getByRole('heading', { name: 'Restaurant management', exact: true })).toBeVisible();
    await page.getByTestId('language-selector').click();
    await page.getByRole('option', { name: 'Română', exact: true }).click();
    expect(errors).toEqual([]);
});

test('embedded setup editors fit mobile and keep English grouped navigation', async ({ page }) => {
    test.setTimeout(90000);
    const account = JSON.parse(readFileSync('storage/app/private/browser-account.json', 'utf8'));
    await page.goto('/login');
    await page.getByTestId('language-selector').click();
    await page.getByRole('option', { name: 'Română', exact: true }).click();
    await page.locator('#email').fill(account.email);
    await page.locator('#password').fill(account.password);
    await page.getByRole('button', { name: 'Autentificare', exact: true }).click();
    await expect(page).toHaveURL(/\/app\/locations\//, { timeout: 20000 });
    await page.getByTestId('language-selector').click();
    await page.getByRole('option', { name: 'English', exact: true }).click();
    const base = `/app/locations/${account.location}`;
    await page.setViewportSize({ width: 390, height: 844 });
    for (const step of ['hours', 'delivery', 'menu', 'branding', 'staff', 'locations']) {
        await page.goto(base + '/setup/' + step);
        expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), `Overflow in ${step}`).toBe(true);
        await expect(page.locator('header')).toHaveCount(1);
    }
    await page.getByRole('button', { name: 'Open navigation', exact: true }).click();
    await expect(page.getByRole('navigation', { name: 'Restaurant navigation' }).getByRole('link').first()).toHaveText('Restaurant setup');
    await page.screenshot({ path: 'test-results/wizard-navigation-mobile.png', fullPage: true });
    await page.getByRole('button', { name: 'Open navigation', exact: true }).click();
    await page.getByTestId('language-selector').click();
    await page.getByRole('option', { name: 'Română', exact: true }).click();
});
