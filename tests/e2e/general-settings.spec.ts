import { test, expect as baseExpect } from '@playwright/test';
import { readFileSync } from 'node:fs';
const expect = baseExpect.configure({ timeout: 20000 });
const account = JSON.parse(
    readFileSync(process.env.ZF_SERVICES_FIXTURE ?? 'storage/app/private/browser-services.json', 'utf8'),
);
test('location formats and public display settings save inside the setup wizard on mobile', async ({ page }) => {
    test.setTimeout(90000);
    const errors: string[] = [];
    page.on('pageerror', (e) => errors.push(e.message));
    await page.goto('/login');
    await page.locator('#email').fill(account.email);
    await page.locator('#password').fill(account.password);
    await page.getByRole('button', { name: 'Autentificare', exact: true }).click();
    await expect(page).toHaveURL(/\/app\/locations\//);
    await page.goto(`/app/locations/${account.location}/general-settings`);
    await page.getByRole('combobox', { name: 'Format dată', exact: true }).click();
    await page.getByRole('option', { name: '2026-10-27', exact: true }).click();
    await page.getByRole('combobox', { name: 'Format dată și oră', exact: true }).click();
    await page.getByRole('option', { name: /^2026-10-27 \d{2}:05:09$/, exact: true }).click();
    await page.getByRole('switch', { name: 'Afișează telefonul', exact: true }).uncheck();
    await page.getByRole('switch', { name: 'Afișează fotografiile produselor', exact: true }).uncheck();
    await page.getByRole('button', { name: 'Salvează', exact: true }).click();
    await expect(page.getByRole('status').filter({ hasText: 'Setările generale au fost salvate.' })).toBeVisible();
    await page.reload();
    await expect(page.getByRole('switch', { name: 'Afișează telefonul', exact: true })).not.toBeChecked();
    await expect(page.getByRole('combobox', { name: 'Format dată', exact: true })).toHaveText('2026-10-27');
    await page.goto(`/store/${account.location}`);
    await expect(page.getByTestId('menu-product-card').first()).toBeVisible();
    await expect(page.getByTestId('menu-product-photo')).toHaveCount(0);
    await page.setViewportSize({ width: 390, height: 844 });
    await page.goto(`/app/locations/${account.location}/setup/general`);
    await expect(page.getByRole('heading', { name: 'Setări generale', exact: true })).toBeVisible();
    await page.getByRole('switch', { name: 'Afișează telefonul', exact: true }).check();
    await page.getByRole('switch', { name: 'Afișează fotografiile produselor', exact: true }).check();
    await page.getByRole('button', { name: 'Salvează', exact: true }).click();
    await expect(page.getByRole('status').filter({ hasText: 'Setările generale au fost salvate.' })).toBeVisible();
    await expect(page).toHaveURL(/\/setup\/general$/);
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
    await page.screenshot({ path: 'test-results/general-settings-mobile.png', fullPage: true });
    await page.getByRole('combobox', { name: 'Format dată', exact: true }).click();
    await page.getByRole('option', { name: '27.10.2026', exact: true }).click();
    await page.getByRole('combobox', { name: 'Format dată și oră', exact: true }).click();
    await page.getByRole('option', { name: /^27\.10\.2026 \d{2}:05$/, exact: true }).click();
    await page.getByRole('button', { name: 'Salvează', exact: true }).click();
    await expect(page.getByRole('status').filter({ hasText: 'Setările generale au fost salvate.' })).toBeVisible();
    expect(errors).toEqual([]);
});
