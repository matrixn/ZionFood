import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';

test('platform console provides actionable statistics, directories, bilingual help and mobile navigation', async ({ page }) => {
    test.skip(process.env.ZF_PLATFORM_E2E !== '1', 'Requires the isolated platform administrator fixture.');
    test.setTimeout(120000);
    page.setDefaultTimeout(15000);
    await page.context().addCookies([{name: 'zf_locale', value: 'ro', url: process.env.ZF_E2E_URL ?? 'http://localhost:8000'}]);
    const account = JSON.parse(readFileSync(process.env.ZF_LEADS_ADMIN!, 'utf8'));
    const errors: string[] = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.setViewportSize({width: 1440, height: 1040});
    await page.goto('/login');
    await page.locator('#email').fill(account.email);
    await page.locator('#password').fill(account.password);
    await page.getByRole('button', {name:'Autentificare',exact:true}).click();
    await expect(page).not.toHaveURL(/\/login$/);
    await page.goto('/admin');
    await expect(page.getByRole('heading', {name:'Centrul de control',exact:true})).toBeVisible();
    await expect(page.getByText('Valoarea comenzilor finalizate', {exact:true})).toBeVisible();
    await expect(page.locator('.admin-hero')).toContainText('RON');
    await expect(page.locator('.admin-hero')).toContainText('EUR');
    await page.locator('#admin-period').focus();
    await page.keyboard.press('F1');
    await expect(page.getByRole('tooltip')).toContainText('UTC');
    await page.keyboard.press('Escape');
    await page.getByRole('combobox', {name: 'Perioada raportată', exact:true}).click();
    await page.getByRole('option', {name:'7 zile',exact:true}).click();
    await expect(page).toHaveURL(/days=7/);
    await page.getByRole('button', {name:'Intrări UTM',exact:true}).click();
    await page.getByText('Vezi datele graficului',{exact:true}).click();
    await expect(page.locator('details tbody tr')).toHaveCount(7);
    await page.getByText('Vezi datele graficului',{exact:true}).click();
    await page.screenshot({path: 'storage/app/private/admin-0046-20261031/dashboard-desktop.png',fullPage:true,animations:'disabled'});
    const navigation = page.getByRole('navigation', {name: 'Navigare administrare generală'});
    await navigation.getByRole('link', {name:'Organizații și restaurante',exact:true}).click();
    await expect(page.getByRole('heading', {name:'Organizații și restaurante',exact:true})).toBeVisible();
    await page.locator('#org-search').fill('Atelier Bistro');
    await page.keyboard.press('Tab');
    await expect(page.getByRole('combobox', {name:'Abonament',exact:true})).toBeFocused();
    await page.getByRole('button', {name:'Aplică filtrele',exact:true}).click();
    await expect(page.locator('.admin-table tbody tr')).toHaveCount(1);
    await page.locator('.admin-table').getByRole('link',{name:'Atelier Bistro',exact:true}).click();
    await expect(page.getByRole('heading',{name:'Atelier Bistro',exact:true,level:1})).toBeVisible();
    await expect(page.getByRole('heading',{name:'Echipă și acces',exact:true})).toBeVisible();
    await navigation.getByRole('link',{name:'Conturi și acces',exact:true}).click();
    await page.locator('#user-search').fill(account.email);
    await page.getByRole('button',{name:'Aplică filtrele',exact:true}).click();
    await expect(page.locator('.admin-table tbody tr')).toHaveCount(1);
    await expect(page.locator('.admin-table tbody')).toContainText('Administrator platformă');
    await navigation.getByRole('link',{name:'Monitorizare operațională',exact:true}).click();
    await page.getByRole('combobox',{name:'Stare',exact:true}).click();
    await page.getByRole('option',{name:'Eșuat',exact:true}).click();
    await expect(page).toHaveURL(/status=failed/);
    await expect(page.locator('.admin-table tbody tr').first()).toContainText('Eșuat');
    await page.screenshot({path:'storage/app/private/admin-0046-20261031/operations-desktop.png',fullPage:true,animations:'disabled'});
    await page.getByTestId('language-selector').click();
    await page.getByRole('option',{name:'English',exact:true}).click();
    await expect(page.getByRole('heading',{name:'Operational monitoring',exact:true})).toBeVisible();
    await page.reload();
    await expect(page.locator('html')).toHaveAttribute('lang','en');
    await page.goto('/admin');
    await expect(page.getByRole('heading',{name:'Control centre',exact:true})).toBeVisible();
    await page.setViewportSize({width:390,height:844});
    expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
    await page.getByRole('button',{name:'Open navigation',exact:true}).click();
    const drawer = page.getByRole('dialog');
    await expect(drawer).toBeVisible();
    await drawer.getByRole('link',{name:'Accounts & access',exact:true}).click();
    await expect(drawer).not.toBeVisible();
    await expect(page.getByRole('heading',{name:'Accounts & access',exact:true})).toBeVisible();
    expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
    await page.screenshot({path:'storage/app/private/admin-0046-20261031/accounts-mobile.png',fullPage:true,animations:'disabled'});
    await page.goto('/admin');
    await page.screenshot({path:'storage/app/private/admin-0046-20261031/dashboard-mobile.png',fullPage:true,animations:'disabled'});
    await page.setViewportSize({width:1440,height:1040});
    await page.getByRole('button',{name:'Toggle color theme',exact:true}).click();
    await expect(page.locator('html')).toHaveClass(/dark/);
    await page.screenshot({path:'storage/app/private/admin-0046-20261031/dashboard-dark.png',fullPage:true,animations:'disabled'});
    await page.getByTestId('language-selector').click();
    await page.getByRole('option',{name:'Română',exact:true}).click();
    expect(errors).toEqual([]);
});
