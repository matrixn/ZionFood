import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';

test('resets with a reviewed confirmation and retained history then publishes a fresh import', async ({ page }) => {
    test.skip(process.env.ZF_IMPORT_RESET_E2E !== '1', 'Requires the private reset fixture.');
    test.setTimeout(120000);
    page.setDefaultTimeout(15000);
    const account = JSON.parse(readFileSync(process.env.ZF_RESET_ACCOUNT!, 'utf8'));
    const errors: string[] = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto('/login');
    await page.locator('#email').fill(account.email);
    await page.locator('#password').fill(account.password);
    await page.getByRole('button',{name:'Autentificare',exact:true}).click();
    await expect(page).toHaveURL(/\/app\/locations\//);
    const base = `/app/locations/${account.location}/migration-center`;
    await page.goto(base);
    await page.getByRole('button',{name:'Resetează importurile',exact:true}).click();
    const dialog = page.getByRole('dialog');
    await expect(page.getByRole('dialog',{name:'Un nou început pentru import',exact:true})).toBeVisible();
    await expect(dialog.getByRole('button',{name:'Confirmă resetarea',exact:true})).toBeDisabled();
    await expect(dialog.getByRole('checkbox',{name:'Revino și asupra datelor restaurantului importate',exact:true})).toBeChecked();
    await expect(dialog).toContainText('Numele restaurantului');
    await page.setViewportSize({width:390,height:844});
    const confirmation = dialog.getByRole('textbox',{name:'Scrie RESET pentru a confirma',exact:true});
    await confirmation.fill('reset');
    await expect(dialog.getByRole('button',{name:'Confirmă resetarea',exact:true})).toBeDisabled();
    await confirmation.focus();
    await page.keyboard.press('F1');
    await expect(page.getByRole('tooltip')).toContainText('majuscule');
    await page.keyboard.press('Escape');
    await confirmation.fill('RESET');
    const confirmButton = dialog.getByRole('button',{name:'Confirmă resetarea',exact:true});
    await expect(confirmButton).toBeEnabled();
    const box = await confirmButton.boundingBox();
    expect(box!.y + box!.height).toBeLessThanOrEqual(844);
    expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
    await page.screenshot({path:'storage/app/private/import-reset-0047-20261101/reset-mobile.png',fullPage:true,animations:'disabled'});
    await confirmButton.click();
    await expect(dialog).not.toBeVisible();
    await expect(page.getByText('Importurile au fost resetate',{exact:true})).toBeVisible();
    await page.reload();
    await page.locator('summary').filter({hasText:'Importuri recente'}).click();
    await page.getByRole('button').filter({hasText:'Resetat · istoric păstrat'}).first().click();
    await expect(page.getByRole('heading',{name:'Resetat · istoric păstrat',exact:true})).toBeVisible();
    await expect(page.getByRole('button',{name:'Revino la meniul anterior',exact:true})).toHaveCount(0);
    await page.setViewportSize({width:1440,height:1000});
    await page.screenshot({path:'storage/app/private/import-reset-0047-20261101/reset-history.png',fullPage:true,animations:'disabled'});
    await page.getByRole('combobox',{name:'Sursa meniului',exact:true}).click();
    await page.getByRole('option',{name:'Fișier JSON exportat anterior (max. 5 MB)',exact:true}).click();
    const source = JSON.parse(readFileSync('tests/Fixtures/gloriafood-menu.json','utf8'));
    source.currency = 'RON';
    const clean = JSON.stringify(source, (key,value) => key === 'menu_item_nutritional_values' ? undefined : value);
    await page.locator('input[type=file]').setInputFiles({name:'menu.json',mimeType:'application/json',buffer:Buffer.from(clean)});
    await page.getByRole('checkbox',{name:'Am dreptul de a importa meniul acestui restaurant.',exact:true}).check();
    await page.getByRole('button',{name:'Preia și verifică',exact:true}).click();
    await expect(page.getByRole('heading',{name:'Pregătit pentru verificare',exact:true})).toBeVisible();
    await page.getByRole('checkbox',{name:'Am verificat prețurile, dimensiunile, regulile, alergenii, nutriția și avertismentele.',exact:true}).check();
    await page.getByRole('button',{name:'Publică meniul',exact:true}).click();
    await page.getByRole('dialog').getByRole('button',{name:'Publică meniul',exact:true}).click();
    await expect(page.getByRole('dialog')).not.toBeVisible();
    await expect(page.getByRole('heading',{name:'Publicat',exact:true})).toBeVisible();
    expect(errors).toEqual([]);
});
