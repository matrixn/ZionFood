import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';

test('service prerequisites open reservation and table configuration inside the current location wizard', async ({ page }) => {
    test.skip(process.env.ZF_SETUP_LINKS_E2E !== '1', 'Requires the private setup fixture.');
    const account = JSON.parse(readFileSync(process.env.ZF_SETUP_LINKS_ACCOUNT!, 'utf8'));
    const errors: string[] = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto('/login');
    await page.locator('#email').fill(account.email);
    await page.locator('#password').fill(account.password);
    await page.getByRole('button',{name:'Autentificare',exact:true}).click();
    await expect(page).toHaveURL(/\/app\/locations\//);
    const base = `/app/locations/${account.location}/setup`;
    await page.goto(base + '/services');
    const reservations = page.getByRole('link',{name:'Configurează regulile de rezervare',exact:true});
    const tables = page.getByRole('link',{name:'Configurează sălile și mesele',exact:true});
    await expect(reservations).toBeVisible();
    await expect(tables).toBeVisible();
    await reservations.click();
    await expect(page).toHaveURL(base + '/reservations');
    await expect(page.getByTestId('setup-step-heading')).toHaveText('Reguli de rezervare');
    await expect(page.locator('header')).toHaveCount(1);
    await page.goto(base + '/services');
    await tables.click();
    await expect(page).toHaveURL(base + '/seating');
    await expect(page.getByTestId('setup-step-heading')).toHaveText('Săli, mese și locuri');
    await page.goto(base + '/services');
    await page.setViewportSize({width:390,height:844});
    await expect(reservations).toBeVisible();
    await expect(tables).toBeVisible();
    expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
    await page.screenshot({path:'storage/app/private/setup-links-0048-20261101/services-mobile.png',fullPage:true,animations:'disabled'});
    await page.getByTestId('language-selector').click();
    await page.getByRole('option',{name:'English',exact:true}).click();
    await page.getByRole('link',{name:'Configure reservation rules',exact:true}).click();
    await expect(page).toHaveURL(base + '/reservations');
    await page.goto(base + '/services');
    await page.getByRole('link',{name:'Configure rooms and tables',exact:true}).click();
    await expect(page).toHaveURL(base + '/seating');
    expect(errors).toEqual([]);
});
